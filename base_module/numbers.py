# Integer
integer_number = 10

# Float
float_number = 1.1

print(f'The number {integer_number} is of type {type(integer_number)}')
print(f'The number {float_number} is of type {type(float_number)}')

# Sum (+)
sum_result = 1 + 2
print(f'Sum: 1 + 2 = {sum_result}')

# Subtraction (-)
subtraction_result = 2 - 1
print(f'Subtraction: 2 - 1 = {subtraction_result}')

# Multiplication (*)
multiplication_result = 2 * 2
print(f'Multiplication: 2 * 2 = {multiplication_result}')

# Division (/)
division_result = 4 / 2
print(f'Division: 4 / 2 = {division_result}')

# Floor Division (//)
floor_division_result = 6 // 2  # Integer division
print(f'Floor Division: 6 // 2 = {floor_division_result}')

# Modulus (%)
modulus_result = 10 % 3
print(f'Modulus: 10 % 3 = {modulus_result}')

# Exponentiation (**)
exponentiation_result = 2 ** 3
print(f'Exponentiation: 2 ** 3 = {exponentiation_result}')
